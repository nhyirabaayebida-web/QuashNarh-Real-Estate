/** Writes placeholder PDFs for a seeded submission and returns their URLs. */
async function seedDocuments(n: number, owner: string): Promise<NewSubmission["documents"]> {
  const dir = path.join(process.cwd(), "uploads");
  await mkdir(dir, { recursive: true });
  const docs: { type: string; label: string; path: string }[] = [];
  for (const type of ["title", "sitePlan", "idCard", "taxReceipt"] as const) {
    const filename = `sub-seed-${n}-${type}.pdf`;
    await writeFile(path.join(dir, filename), pdfBytes(`${DOC_LABELS[type]} - ${owner}`));
    docs.push({ type, label: DOC_LABELS[type], path: `/uploads/${filename}` });
  }
  return docs;
}

